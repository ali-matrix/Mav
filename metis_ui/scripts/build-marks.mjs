// marks/*.svg is the one drawing of each dashboard's mark. This writes everything else:
//   src/marks.ts                     what the kit's <AppMark> draws
//   <app>/.../AppMark.tsx            the same drawing, for apps not on the kit yet
//   metis_thinking/branding/*.svg    the white files, for anything outside the apps
// node scripts/build-marks.mjs          write
// node scripts/build-marks.mjs --check  exit 1 if any of them no longer matches marks/
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const kit = new URL("../", import.meta.url);
const repo = new URL("../", kit);
const check = process.argv.includes("--check");

// Apps with their own header, until each moves onto the kit. Delete a row when it does.
const LEGACY = {
  "acta/components/AppMark.tsx": ["acta", "Acta"],
  "agora/components/AppMark.tsx": ["agora", "Agora"],
  "argus/app/components/AppMark.tsx": ["argus", "Argus"],
  "chronos/components/AppMark.tsx": ["chronos", "Chronos"],
  "inadashboard/src/components/AppMark.tsx": ["production", "Production"],
  "saga/components/AppMark.tsx": ["saga", "Saga"],
};

const names = readdirSync(new URL("marks/", kit)).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)).sort();
const raw = Object.fromEntries(names.map((n) => [n, readFileSync(new URL(`marks/${n}.svg`, kit), "utf8").replace(/\r\n/g, "\n")]));
// The drawing alone: the note and the wrapping <svg> go, whitespace between tags collapses.
const art = (n) => raw[n].replace(/<!--[\s\S]*?-->/g, "").replace(/^\s*<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/>\s+</g, "><").trim();

const out = {};
out["metis_ui/src/marks.ts"] = `// GENERATED by scripts/build-marks.mjs from marks/*.svg. Edit the drawing there, not here.
export type AppMarkName = ${names.map((n) => JSON.stringify(n)).join(" | ")};

export const MARK_ART: Record<AppMarkName, string> = {
${names.map((n) => `  ${n}: ${JSON.stringify(art(n))},`).join("\n")}
};
`;

const SVG_PROPS = `viewBox="0 0 64 64" fill="none" stroke="currentColor" strokeWidth={4} strokeLinecap="round" strokeLinejoin="round"`;
for (const [path, [name, label]] of Object.entries(LEGACY)) {
  out[path] = `// GENERATED by metis_ui/scripts/build-marks.mjs from metis_ui/marks/${name}.svg. Edit it there.
// White on the header and rail in both themes, the same on every dashboard.
import type React from "react";

const ART = ${JSON.stringify(art(name))};

export default function AppMark({ size = 36, className = "", style }: {
  size?: number; className?: string; style?: React.CSSProperties;
}) {
  return (
    <svg width={size} height={size} ${SVG_PROPS} role="img" aria-label="${label}"
      className={\`shrink-0 \${className}\`} style={{ color: "#FFFFFF", ...style }} dangerouslySetInnerHTML={{ __html: ART }} />
  );
}
`;
}

for (const n of names) {
  out[`metis_thinking/branding/${n}_teams_outline.svg`] = raw[n].replace(/<!--[\s\S]*?-->\n?\s*/g, "").replaceAll("currentColor", "#FFFFFF");
}

const stale = [];
for (const [path, text] of Object.entries(out)) {
  const url = new URL(path, repo);
  // Outside the Metis monorepo (a shared copy of the kit) only the kit's own files exist.
  if (!existsSync(new URL(".", url))) continue;
  const same = existsSync(url) && readFileSync(url, "utf8").replace(/\r\n/g, "\n") === text;
  if (same) continue;
  if (check) stale.push(path);
  else writeFileSync(url, text);
}
if (stale.length) { console.error(`Marks out of date, run node scripts/build-marks.mjs:\n  ${stale.join("\n  ")}`); process.exit(1); }
console.log(`@metis/ui: ${names.length} marks, ${Object.keys(out).length} files ${check ? "in step" : "written"}.`);
